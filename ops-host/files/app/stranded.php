<?php
// auto-pr-stranded-branches on the host (user's decision 1405-08-07: zero Actions, the clock lives on ops).
// Same rules as Sys.scripts/auto-pr-stranded-branches.sh + lib/branch-classify.sh in the private repo, through the
// GitHub REST API only: every claude/* branch with hand-written, unmerged work and no PR (open or closed) gets one
// PR. Never merges, never closes. Runs once a day from tick.php. Token: OPS_GITHUB_TOKEN in ../secrets.php
// (fine-grained: Contents read/write + Pull requests read/write on the holding's repos).
require_once __DIR__ . '/lib.php';    // ops_secret()

const OPS_STRANDED_REPO = 'lili2001mua-cmd/Agent-Project-Backup';
const OPS_STRANDED_EXCLUDE = ['claude/intake-pool'];
const OPS_STRANDED_HOUR = 3;          // UTC, as the retired cron ('0 3 * * *')

function ops_gh(string $method, string $path, ?array $body = null, string $accept = 'application/vnd.github+json'): array {
    $ch = curl_init('https://api.github.com' . $path);
    $h = ['Authorization: Bearer ' . ops_secret('OPS_GITHUB_TOKEN'), 'Accept: ' . $accept,
          'X-GitHub-Api-Version: 2022-11-28', 'User-Agent: ops-hohedoc'];
    if ($body !== null) $h[] = 'Content-Type: application/json';
    curl_setopt_array($ch, [CURLOPT_RETURNTRANSFER => true, CURLOPT_TIMEOUT => 30, CURLOPT_CUSTOMREQUEST => $method,
        CURLOPT_HTTPHEADER => $h]);
    if ($body !== null) curl_setopt($ch, CURLOPT_POSTFIELDS, json_encode($body, JSON_UNESCAPED_UNICODE));
    $raw = curl_exec($ch);
    $code = (int) curl_getinfo($ch, CURLINFO_HTTP_CODE);
    curl_close($ch);
    return [$code, $accept === 'application/vnd.github.raw' ? (string) $raw : json_decode((string) $raw, true)];
}

// Generated (re-buildable) files: the `git add` block of Sys.scripts/sync-discovery-lists.sh — the same single
// source bc_generated_paths() reads. No parallel list here.
function ops_generated_paths(): array {
    [$code, $src] = ops_gh('GET', '/repos/' . OPS_STRANDED_REPO . '/contents/Sys.scripts/sync-discovery-lists.sh?ref=main', null, 'application/vnd.github.raw');
    if ($code !== 200) return [];
    $out = []; $on = false;
    foreach (explode("\n", $src) as $line) {
        if (!$on && str_contains($line, 'git add ')) $on = true;
        if (!$on) continue;
        $l = preg_replace(['/^\s*git add /', '/\\\\$/', '/2>\/dev\/null.*/', '/\|\|\s*true/'], '', $line);
        foreach (preg_split('/\s+/', trim($l)) as $p) { $p = trim($p, '"'); if ($p !== '') $out[$p] = true; }
        if (!preg_match('/\\\\\s*$/', $line)) break;
    }
    return $out;
}

function ops_stranded_run(bool $dry = false): array {
    $repo = OPS_STRANDED_REPO; $owner = explode('/', $repo)[0];
    $sum = ['opened' => 0, 'has_pr' => 0, 'no_unique' => 0, 'excluded' => 0, 'errors' => 0, 'dry' => $dry, 'items' => []];
    $gen = ops_generated_paths();
    if (!$gen) { $sum['errors']++; $sum['items'][] = 'generated-list unreadable'; return $sum; }
    $branches = [];
    for ($page = 1; $page <= 10; $page++) {
        [$code, $r] = ops_gh('GET', "/repos/$repo/branches?per_page=100&page=$page");
        if ($code !== 200 || !is_array($r)) { $sum['errors']++; $sum['items'][] = "branches http=$code"; return $sum; }
        foreach ($r as $b) if (str_starts_with($b['name'], 'claude/')) $branches[] = $b['name'];
        if (count($r) < 100) break;
    }
    foreach ($branches as $name) {
        if (in_array($name, OPS_STRANDED_EXCLUDE, true)) { $sum['excluded']++; continue; }
        [$code, $c] = ops_gh('GET', "/repos/$repo/compare/main..." . rawurlencode($name));
        if ($code !== 200) { $sum['errors']++; $sum['items'][] = "$name compare http=$code"; continue; }
        $ahead = (int) ($c['ahead_by'] ?? 0);
        $files = array_map(fn($f) => $f['filename'], $c['files'] ?? []);
        $hand = array_values(array_filter($files, fn($f) => !isset($gen[$f])));
        if ($ahead === 0 || !$files || !$hand) { $sum['no_unique']++; continue; }        // MERGED · SAME · GENERATED
        [$code, $prs] = ops_gh('GET', "/repos/$repo/pulls?state=all&per_page=1&head=" . rawurlencode("$owner:$name"));
        if ($code !== 200 || !is_array($prs)) { $sum['errors']++; $sum['items'][] = "$name pulls http=$code"; continue; }
        if ($prs) { $sum['has_pr']++; continue; }
        $sum['items'][] = "$name ($ahead commits, " . count($hand) . ' hand-written)';
        if ($dry) { $sum['opened']++; continue; }
        $body = "این PR خودکار توسطِ هاستِ `ops.hohedoc.ir` (جایِ workflowِ `auto-pr-stranded-branches`) باز شده — این برنچ **$ahead کامیتِ\nمنحصربه‌فرد** نسبت به `main` دارد و تا امروز هیچ Pull Request ای (باز یا بسته) برایش ساخته نشده بود.\n\n"
              . "⚠️ ممکن است این برنچ از `main` عقب باشد و پیش از مرج نیاز به sync/رفعِ تعارض داشته باشد.\n\n"
              . "این PR فقط **باز شده**؛ auto-merge نمی‌شود — بررسی/مرج/بستن دستِ خودِ شماست.\n\n---\n_Generated by [Claude Code](https://claude.ai/code) — ops.hohedoc.ir_";
        [$code, $pr] = ops_gh('POST', "/repos/$repo/pulls", ['title' => "برنچِ رهاشده: $name ($ahead کامیتِ یکتا) — نیازِ بررسی/مرج",
            'head' => $name, 'base' => 'main', 'body' => $body]);
        if ($code === 201) $sum['opened']++; else { $sum['errors']++; $sum['items'][] = "$name create http=$code"; }
    }
    $sum['branches'] = count($branches);
    return $sum;
}

// Called from tick.php: once per UTC day inside OPS_STRANDED_HOUR. No token ⇒ recorded, not silent.
function ops_stranded_tick(): void {
    $f = ops_var('stranded.json');
    $st = @json_decode((string) @file_get_contents($f), true) ?: [];
    if (ops_secret('OPS_GITHUB_TOKEN') === '') { $st['token'] = false; file_put_contents($f, json_encode($st)); return; }
    $st['token'] = true;
    $due = (int) gmdate('G') === OPS_STRANDED_HOUR && time() - (int) ($st['at'] ?? 0) > 20 * 3600;
    if (!$due) { file_put_contents($f, json_encode($st)); return; }
    $r = ops_stranded_run(false);
    $st = ['token' => true, 'at' => time(), 'result' => $r];
    file_put_contents($f, json_encode($st, JSON_UNESCAPED_UNICODE));
    ops_log("stranded opened={$r['opened']} errors={$r['errors']}");
    if ($r['errors'] > 0) ops_telegram("⚠️ هاستِ ops: بررسیِ برنچ‌های رهاشده {$r['errors']} خطا داد. جزئیات: https://ops.hohedoc.ir/status.php");
}
